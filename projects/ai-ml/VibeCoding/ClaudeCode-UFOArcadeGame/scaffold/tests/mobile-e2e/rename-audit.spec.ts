// Implements docs/mobile/PRD-mobile.md M9.1 (Amended 2026-09-25, v1.3/v1.4) and
// docs/PRD-addendum-v4.md F22 AC5/AC13 (the rename to "Shield vs Robots" /
// "ShieldMan" / "robots"): a static text-content audit of the actual BUILT Android
// assets, not the source (F22 AC12 explicitly allows old names to survive as
// non-player-facing source identifiers like `drawVanguard`/`VANGUARD_BLUE` - those
// must never leak into player-facing output, but this test cannot assume they were
// stripped; it only asserts the built artifact is clean).
//
// M9.1's own test: "install the debug build -> launcher label reads 'Shield vs
// Robots'; a search of the Android resources, bundled web assets and listing text
// for 'Sentinel' returns no player-visible hit." This runs the "bundled web assets"
// and "Android resources" half of that search statically (no emulator needed, so it
// runs in CI); the installed-APK launcher-label check itself is in
// docs/mobile/tests/manual-only-criteria.md.
//
// No browser is used here - this is a plain filesystem check, kept in this suite so
// one `npm run test:e2e:mobile` run covers it alongside the rest of the
// mobile-only tests. Uses a hand-rolled directory walk (not `fs.globSync`, which is
// still experimental on the Node 22 the CI `mobile-e2e` job pins) so this test's
// Node-version support matches the rest of the repo's tooling exactly.

import { test, expect } from '@playwright/test';
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

// playwright.mobile.config.ts has no `import.meta`/`__dirname` use elsewhere, and the
// eslint `no-restricted-syntax` rule reserves `import.meta` for src/main.ts (M-ADR-0002);
// Playwright always runs from the repo root (its own config resolves `testDir` and
// `webServer.command` relative to it), so an explicit cwd-relative path is both simpler
// and consistent with that rule.
const REPO_ROOT = path.resolve(process.cwd());
const SCANNABLE_EXTENSIONS = new Set(['.js', '.html', '.css']);

// Case-insensitive; F22 AC1/AC5 also bans the dropped subtitle "Shield Invaders".
const BANNED_PATTERNS: Array<{ label: string; pattern: RegExp }> = [
  { label: 'Vanguard', pattern: /vanguard/i },
  { label: 'Sentinel(s)', pattern: /sentinel/i },
  { label: '"Shield Invaders" subtitle', pattern: /shield invaders/i },
];

function listFilesRecursive(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    const stats = statSync(full);
    if (stats.isDirectory()) {
      out.push(...listFilesRecursive(full));
    } else if (SCANNABLE_EXTENSIONS.has(path.extname(full))) {
      out.push(full);
    }
  }
  return out;
}

function scanFile(filePath: string): Array<{ label: string; match: string }> {
  const text = readFileSync(filePath, 'utf8');
  const hits: Array<{ label: string; match: string }> = [];
  for (const { label, pattern } of BANNED_PATTERNS) {
    const match = text.match(pattern);
    if (match) hits.push({ label, match: match[0] });
  }
  return hits;
}

test.describe('F22/M9.1 rename audit - built Android assets contain no old names', () => {
  test('dist-android (bundled web assets) has no player-visible "Vanguard"/"Sentinel"/"Shield Invaders"', () => {
    const distAndroid = path.join(REPO_ROOT, 'dist-android');
    test.skip(!existsSync(distAndroid), 'dist-android is built by `npm run build:android` before this suite runs');

    const files = listFilesRecursive(distAndroid);
    expect(files.length, 'no dist-android build output found to scan').toBeGreaterThan(0);

    const offenders: string[] = [];
    for (const file of files) {
      for (const hit of scanFile(file)) {
        offenders.push(`${path.relative(REPO_ROOT, file)}: ${hit.label} ("${hit.match}")`);
      }
    }
    expect(offenders, offenders.join('\n')).toEqual([]);
  });

  test('Android resources (launcher label, strings.xml) use "Shield vs Robots" only', () => {
    const stringsXml = path.join(REPO_ROOT, 'android', 'app', 'src', 'main', 'res', 'values', 'strings.xml');
    test.skip(!existsSync(stringsXml), 'android/ is generated by `npx cap sync android`');

    const offenders = scanFile(stringsXml).map((hit) => `${hit.label} ("${hit.match}")`);
    expect(offenders, offenders.join('\n')).toEqual([]);

    // M9.1's exact positive assertion: the launcher label (`app_name`) is exactly
    // "Shield vs Robots".
    const text = readFileSync(stringsXml, 'utf8');
    const appNameMatch = text.match(/<string name="app_name">([^<]*)<\/string>/);
    expect(appNameMatch?.[1]).toBe('Shield vs Robots');
  });
});
